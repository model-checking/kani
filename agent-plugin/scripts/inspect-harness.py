"""Describe the Kani harnesses in Rust sources, and flag structural problems.

For each harness, reports its kind (`proof` / `proof_for_contract`), Kani attributes
(unwind, stubs, solver, should_panic, ...), how many nondeterministic inputs, assumptions,
assertions, and covers it has, and the functions it calls. Flags:

- no-nondeterminism: no `kani::any()` (or `any_where`); the harness checks one concrete
  execution, like a unit test, not all inputs.
- no-assertions: no user assertion or cover; only Kani's default safety checks apply.
  That is fine for UB/panic-freedom proofs, but say so when reporting the result.
- loop-without-unwind: the harness body has a loop but no `#[kani::unwind]`; verification
  may not terminate, or need `--default-unwind`.
- should-panic: the harness passes only if it panics; report it that way.
- branches-without-covers: the harness branches (`if`, `match`, `unwrap_err`, `unwrap_or`, ...)
  but has fewer than two covers. A branch its inputs never reach is checked on no execution,
  and no verdict shows it: add `kani::cover!` in each branch.

Counts include the Kani-only helper functions a harness calls and its `#[kani::stub]`
replacements, so inputs and assumptions made in helpers are attributed to the harness.

This is a static, text-based scan that needs no toolchain. It cannot see harnesses generated by
macros: pass `--list-json kani-list.json` (from `cargo kani list --format json`) to report the
harnesses Kani knows about that the scan did not find.

On large crates, start with `--summary` (counts and the names of flagged harnesses) or
`--flagged-only`.

Usage:
    inspect-harness.py PATH... [--harness NAME] [--summary | --flagged-only] [--list-json FILE]
"""

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kani_plugin_lib import (  # noqa: E402
    CALL, emit, find_root, harnesses_of, helper_closure, helper_index, kani_only_files, parse_functions, rust_files)

ANY = re.compile(r"\bkani::any(?:_where)?\b|\bany_(?:modifies|slice_of_array)\b|\bkani::vec::(?:any|exact)_vec\b"
                 r"|\bkani::bounded_any\b|\bkani::slice::any_slice_of_array(?:_mut)?\b|\bany_array\b"
                 r"|\bArbitrary\s*>?\s*::\s*any\b|\b[A-Z]\w*::any\s*\(")
ASSUME = re.compile(r"\bkani::assume\s*\(|\bkani::any_where\s*\(")
BRANCH = re.compile(r"\bif\b|\bmatch\b|\.(?:unwrap_err|unwrap_or|unwrap_or_else|map_err)\s*\(")
ASSERT = re.compile(
    r"\b(?:assert|assert_eq|assert_ne|debug_assert|debug_assert_eq|debug_assert_ne)!\s*\(|\bkani::assert\s*\(")
COVER = re.compile(r"\bkani::cover!\s*\(")
LOOP = re.compile(r"\b(?:for|while|loop)\b")
NOT_CALLS = {"if", "while", "for", "match", "return", "Some", "Ok", "Err", "Box::new", "loop", "in"}
MAX_CALLS = 20


def describe(h, helpers=()):
    bodies = [h.body] + [x.body for x in helpers]
    calls = []
    for c in CALL.findall(h.body):
        if c in NOT_CALLS or c.startswith("kani::") or c in calls:
            continue
        calls.append(c)
    counts = {
        "nondet_inputs": sum(len(ANY.findall(b)) for b in bodies),
        "assumptions": sum(len(ASSUME.findall(b)) for b in bodies),
        "assertions": sum(len(ASSERT.findall(b)) for b in bodies),
        "covers": sum(len(COVER.findall(b)) for b in bodies),
    }
    flags = []
    if counts["nondet_inputs"] == 0 and h.kind == "proof" and "stub" not in h.attributes:
        flags.append("no-nondeterminism")
    if counts["assertions"] == 0 and counts["covers"] == 0 and h.kind == "proof":
        flags.append("no-assertions")
    if any(LOOP.search(b) for b in bodies) and "unwind" not in h.attributes:
        flags.append("loop-without-unwind")
    if "should_panic" in h.attributes:
        flags.append("should-panic")
    if BRANCH.search(h.body) and counts["covers"] < 2:
        # A branch the inputs never reach is checked on no execution at all, and no verdict
        # shows it: put a `kani::cover!` in each branch.
        flags.append("branches-without-covers")
    attrs = {k: v for k, v in h.attributes.items() if k not in ("proof", "proof_for_contract")}
    out = {
        "name": h.name,
        "location": f"{h.file}:{h.line}",
        "kind": h.kind,
        "attributes": attrs,
        "counts": counts,
        "calls": calls[:MAX_CALLS],
        "flags": flags,
    }
    if helpers:
        out["helpers"] = [x.name for x in helpers]
    if h.target:
        out["contract_target"] = h.target
    return out


def listed_harnesses(list_json):
    """Harness names from a `cargo kani list --format json` file."""
    doc = json.loads(open(list_json, encoding="utf-8").read())
    names = set()
    for key in ("standard-harnesses", "contract-harnesses"):
        for harnesses in doc.get(key, {}).values():
            names.update(harnesses)
    return names


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("paths", nargs="+", help="Rust files or directories to scan")
    parser.add_argument("--harness", action="append", default=[], help="only describe these harnesses")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--summary", action="store_true", help="only counts and the names of flagged harnesses")
    mode.add_argument("--flagged-only", action="store_true", help="only harnesses with at least one flag")
    parser.add_argument("--list-json", help="`cargo kani list --format json` output, to find unscanned harnesses")
    args = parser.parse_args(argv)
    try:
        targets = list(rust_files(args.paths))
        _, package = find_root(targets[0]) if targets else (None, None)
        crate = list(rust_files([package])) if package else targets
        kani_only = kani_only_files(crate)
        parsed = {f.resolve(): parse_functions(f.read_text(encoding="utf-8", errors="replace"), f,
                                               f.resolve() in kani_only) for f in {*crate, *targets}}
        index = helper_index([fn for fns in parsed.values() for fn in fns])
        harnesses = []
        for f in targets:
            for fn in parsed[f.resolve()]:
                hs = harnesses_of([fn])
                if hs and (not args.harness or fn.name in args.harness):
                    harnesses.append(describe(hs[0], helper_closure(fn, index)))
        missing = None
        if args.list_json:
            found = {h["name"] for h in harnesses}
            missing = sorted(n for n in listed_harnesses(args.list_json) if n.split("::")[-1] not in found)
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    flagged = [h for h in harnesses if h["flags"]]
    if args.summary:
        flag_counts = {}
        for h in flagged:
            for flag in h["flags"]:
                flag_counts.setdefault(flag, []).append(h["name"])
        out = {"harnesses": len(harnesses), "flagged": flag_counts}
    else:
        out = {"harnesses": flagged if args.flagged_only else harnesses}
    if missing is not None:
        out["not_found_in_source"] = missing
        if missing:
            out["note"] = ("Kani lists these harnesses but the scan did not find them in the source; they are "
                           "probably generated by a macro. Inspect the macro definition by hand.")
    emit(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
