"""Confirm a defect, or a fix, with a concrete playback witness.

A witness is a unit test generated by Kani's concrete playback
(`--concrete-playback=inplace`, or `print` and paste) that replays a failing harness with
concrete inputs. A defect counts as confirmed only when its witness actually fails when run,
with the failure Kani reported, and a fix counts as confirmed only when the witness fails on the
code before the fix and passes after it.

Runs `kani playback` for the witness on the current code and, with `--base` or `--base-dir`,
on the code before the change (in a work copy; the witness is copied next to its harness there
if it does not exist yet). Reports one verdict:

- defect-confirmed: the witness fails on the current code with the failure Kani reported
  (no baseline given).
- different-failure: the witness fails, but with another kind of panic than Kani reported.
- fix-confirmed: the witness fails on the baseline and passes on the current code.
- defect-still-present: the witness fails on both.
- witness-does-not-reproduce: the witness passes where it should fail. Native execution does not
  trap every undefined behavior (out-of-bounds pointer arithmetic, invalid pointers): confirm
  such a defect with Miri (`cargo +nightly miri test <test>`) and report it as Kani-only evidence.
- spurious-failure-likely: the harness uses `#[kani::stub]` or `#[kani::stub_verified]`, and the
  real code passes on the witness input, or the replay ends with concrete values left over (the
  stubs consumed nondeterministic values that the real code does not). Playback runs the real
  code, so the failure Kani reported most likely comes from a stub, or a callee contract whose
  `ensures` is too weak.
- not-a-failure-witness: the test replays a `cover` (an input that reaches a cover), not a failure.
- error: the witness could not be built or run; see `output_tail`.

Failures are compared by kind and not by exact text: Kani's description of `assert_eq!`
(a placeholder message), of slice and index errors, of overflow, and of unwrap on `None` differ
from the runtime panic message, so they are matched as classes. A panic that aborts the test
process ("non-unwinding panic") counts as a failure. A hand-written test has no expectation:
pass `--expect TEXT` (the failure's description), or accept that any panic confirms it, which the
output states.

Usage:
    check-witness.py PATH --test NAME [--base REV | --base-dir DIR] [--cargo-arg ARG]...
                     [--expect TEXT] [--work-dir DIR]

The test is replayed with `cargo kani playback --lib` first (doctests and integration tests are
irrelevant to a witness). If the build fails, the script replays in a work copy of the workspace
without the crate's other tests (`#[test]` functions and `#[cfg(test)]` modules; the code under
verification is not changed), with `deny(warnings)` relaxed (an `unexpected_cfgs` warning for
`cfg(kani)` would otherwise be an error), and, when the generated test needs `vec!`/`Vec` that a
`#![no_std]` crate does not have, with `extern crate std` and the imports added to the copy. Work
copies go under `--work-dir` (default: the plugin output directory, `target/kani-plugin/`; see
`KANI_PLUGIN_OUT`), each with its own cargo target directory, so baseline and current builds
never share artifacts. Use `--cargo-arg` for features, packages, or targets.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kani_plugin_lib import (  # noqa: E402
    emit, find_root, join_option_values, kani_env, mirror_workspace, parse_functions, plugin_out_dir,
    rust_files, strip_comments_and_strings, test_only_ranges)

OUTPUT_TAIL_LINES = 40

PANIC = re.compile(r"panicked at ([^\n]+?):(\d+):\d+:\n(.*)")
LEFTOVER = "concrete values left over"

# Panic messages by class: Kani's description of a check and the runtime panic message of the same
# failure rarely have the same text.
MESSAGE_CLASSES = [
    ("assert-eq", re.compile(r"assertion `left (==|!=) right` failed|placeholder message|assert_failed|"
                             r"formatted at runtime", re.I)),
    ("index", re.compile(r"index out of bounds|out of range for slice|slice index starts|range end index|"
                         r"range start index|byte index|is not a char boundary|get_unchecked", re.I)),
    ("overflow", re.compile(r"with overflow|overflow", re.I)),
    ("div-zero", re.compile(r"divide by zero|division by zero|divisor of zero", re.I)),
    ("unwrap-none", re.compile(r"on a `None` value|unwrap.*None|called `Option::unwrap", re.I)),
    ("unwrap-err", re.compile(r"on an `Err` value|called `Result::unwrap|expect", re.I)),
    ("unreachable", re.compile(r"unreachable|internal error: entered unreachable", re.I)),
]


def message_class(message):
    for name, pattern in MESSAGE_CLASSES:
        if pattern.search(message):
            return name
    return None


def panic_of(text):
    """(location, message) of the first panic in a test's output, or None."""
    m = PANIC.search(text)
    return (f"{m.group(1)}:{m.group(2)}", m.group(3).strip()) if m else None


def expected_failure(witness_src):
    """The property a playback test was generated for: (class, description), from its doc
    comment ``/// Check for `assertion`: "attempt to add with overflow"``."""
    m = re.search(r'///\s*Check for `([^`]+)`:\s*"(.*)"\s*$', witness_src, re.M)
    return (m.group(1), m.group(2).strip('"')) if m else (None, None)


def matches(panic, description):
    """True if the panic is the failure Kani reported, False if it is another failure, and None
    when there is no expectation to compare with."""
    if panic is None:
        return False
    if not description:
        return None
    message = panic[1].strip('"')
    if description in message or message in description:
        return True
    a, b = message_class(message), message_class(description)
    if a is None or b is None:
        # An assertion Kani describes as `assertion failed: <expr>` panics with that text.
        return a == b and message.startswith("assertion") and description.startswith("assertion")
    return a == b


def build_problem(text):
    """What kind of build failure a playback output shows, if any."""
    if re.search(r"cannot find (macro `vec`|type `Vec`)|use of undeclared (type|crate or module) `?(Vec|vec|std)", text):
        return "needs-std"
    if re.search(r"unexpected `cfg` condition|`#!\[deny\(warnings\)\]`|deny\(warnings\)", text):
        return "deny-warnings"
    if re.search(r"couldn't read|No such file or directory.*include_(bytes|str)", text):
        return "missing-include"
    return None


def run_once(cwd, single_file, test, cargo_args, env=None):
    if single_file:
        cmd = ["kani", "playback", "-Z", "concrete-playback", *cargo_args, single_file, "--", test]
    else:
        cmd = ["cargo", "kani", "playback", "-Z", "concrete-playback", *cargo_args, "--", test]
    out = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, env=env or kani_env())
    text = out.stdout + out.stderr
    if re.search(r"test result: ok\. [1-9]", text):
        return "passes", text
    aborted = "non-unwinding panic" in text or out.returncode in (-6, 134)
    if "panicked at" in text and (re.search(r"test result: FAILED", text) or aborted):
        return "fails", text
    return "error", text


TARGET_FLAGS = {"--lib", "--bin", "--bins", "--test", "--tests", "--example", "--examples", "--bench", "--benches"}


def run_witness(cwd, single_file, test, cargo_args, env=None, has_lib=True):
    """Run one playback test: "fails", "passes", or "error", the output, and the cargo arguments
    used. The library target is tried first: a witness lives there, and doctests and integration
    tests only add build failures."""
    chosen = {a.split("=")[0] for a in cargo_args} & TARGET_FLAGS
    attempts = [cargo_args]
    if not single_file and not chosen:
        attempts = [[*cargo_args, "--lib"], cargo_args] if has_lib else [cargo_args]
    text = ""
    for args in attempts:
        result, out = run_once(cwd, single_file, test, args, env)
        if result != "error":
            return result, out, args
        text += f"\n--- cargo kani playback {' '.join(args)} ---\n" + out
    return "error", text, attempts[0]


def isolate(package_dir, keep):
    """Remove test-only code other than the test `keep` from the library sources of a copy."""
    for f in rust_files([Path(package_dir) / "src"]):
        src = f.read_text(encoding="utf-8", errors="replace")
        ranges = test_only_ranges(src, keep)
        if ranges:
            for start, end in reversed(ranges):
                src = src[:start] + src[end:]
            f.write_text(src, encoding="utf-8")


def relax_warnings(package_dir):
    """In a copy, turn `deny(warnings)` into `warn(warnings)`: a playback build with `cfg(kani)`
    otherwise fails the crate's own lint policy (`unexpected_cfgs`)."""
    for f in rust_files([Path(package_dir) / "src"]):
        src = f.read_text(encoding="utf-8", errors="replace")
        new = re.sub(r"\b(deny|forbid)\(warnings\)", "warn(warnings)", src)
        if new != src:
            f.write_text(new, encoding="utf-8")


STD_IMPORTS = "use std::{vec, vec::Vec};"


def add_std_imports(package_dir, test):
    """In a copy of a `no_std` crate, make `vec!` and `Vec` available to the generated witness:
    `extern crate std;` at the crate root and the import in the witness's module."""
    package_dir = Path(package_dir)
    for f in rust_files([package_dir / "src"]):
        src = f.read_text(encoding="utf-8", errors="replace")
        for fn in parse_functions(src, f):
            if fn.name != test:
                continue
            if fn.scope == "mod" and fn.scope_start:
                src = src[:fn.scope_start + 1] + f"\n    {STD_IMPORTS}\n" + src[fn.scope_start + 1:]
            else:
                src = file_top_insert(src, STD_IMPORTS)
            f.write_text(src, encoding="utf-8")
            break
    for name in ("lib.rs", "main.rs"):
        root = package_dir / "src" / name
        if root.exists():
            src = root.read_text(encoding="utf-8", errors="replace")
            if "extern crate std" not in src:
                root.write_text(file_top_insert(src, "extern crate std;"), encoding="utf-8")
            break


def file_top_insert(src, line):
    """Insert `line` after the leading inner attributes and comments of a Rust file."""
    lines = src.split("\n")
    i = 0
    while i < len(lines) and (lines[i].startswith("#![") or lines[i].startswith("//") or not lines[i].strip()):
        i += 1
    return "\n".join(lines[:i] + [line] + lines[i:])


def find_test(files, test):
    """The witness test function and the file it is in."""
    for f in files:
        src = f.read_text(encoding="utf-8", errors="replace")
        code = strip_comments_and_strings(src)
        for fn in parse_functions(src, f):
            if fn.name == test:
                # Include the doc comment, which Kani separates from `#[test]` with a blank line:
                # it names the property the witness reproduces.
                start = max(code.rfind(c, 0, fn.start) for c in "{};") + 1
                return f, src[start:fn.end].strip("\n")
    return None, None


def base_text(args, root, path):
    """The text of `path` at the baseline, or None if it does not exist there. `root` is the
    workspace root: baseline directories mirror it (a path relative to the current directory is
    also accepted)."""
    path = Path(path).resolve()
    if args.base_dir:
        for candidate in (Path(args.base_dir) / path.relative_to(root), Path(args.base_dir) / os.path.relpath(path)):
            if candidate.exists():
                return candidate.read_text(encoding="utf-8", errors="replace")
        return None
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=path.parent,
                         capture_output=True, text=True, check=True).stdout.strip()
    rel = path.relative_to(Path(top).resolve()).as_posix()
    out = subprocess.run(["git", "show", f"{args.base}:{rel}"], cwd=top, capture_output=True, text=True)
    return out.stdout if out.returncode == 0 else None


def replayed_harness(witness_src):
    m = re.search(r"concrete_playback_run\s*\(\s*[^,]+,\s*([A-Za-z_][\w:]*)\s*\)", witness_src)
    return m.group(1).split("::")[-1] if m else None


def stubs_of(files, harness):
    """The `#[kani::stub]` and `#[kani::stub_verified]` attributes of a harness."""
    for f in files:
        for fn in parse_functions(f.read_text(encoding="utf-8", errors="replace"), f):
            if fn.name == harness:
                return [f"{n}({a})" for n, a, _ in fn.attributes if n in ("kani::stub", "kani::stub_verified")]
    return []


def with_witness(base_src, witness_src, path):
    """Insert the witness test into the baseline source, right after the harness it replays."""
    m = re.search(r"\bfn\s+(\w+)", witness_src)
    if m and re.search(r"\bfn\s+" + re.escape(m.group(1)) + r"\b", base_src):
        return base_src
    harness = replayed_harness(witness_src)
    for fn in parse_functions(base_src, path):
        if fn.name == harness:
            return base_src[:fn.end] + "\n\n" + witness_src + "\n" + base_src[fn.end:]
    return None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("path", help="Cargo project directory, or the .rs file of a single-file project")
    parser.add_argument("--test", required=True, help="name of the concrete playback test")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--base", help="git revision of the code before the change")
    group.add_argument("--base-dir", help="directory with a copy of the sources before the change "
                       "(the same layout as the workspace)")
    parser.add_argument("--cargo-arg", action="append", default=[],
                        help="argument for `cargo kani playback`, e.g. `--cargo-arg --features --cargo-arg serde` "
                             "(repeatable)")
    parser.add_argument("--expect", help="the failure the witness should reproduce (its description); needed for "
                        "hand-written tests")
    parser.add_argument("--work-dir", help="where to create work copies (default: the plugin output directory)")
    args = parser.parse_args(join_option_values(argv, {"--cargo-arg"}))

    path = Path(args.path)
    root, package = find_root(path)
    single_file = path.name if root is None else None
    files = [path] if single_file else list(rust_files([package]))
    witness_file, witness_src = find_test(files, args.test)
    if witness_file is None:
        print(f"error: no function `{args.test}` found under {path}", file=sys.stderr)
        return 1
    expected_class, expected_desc = expected_failure(witness_src)
    if args.expect:
        expected_desc = args.expect
    result = {"test": args.test, "expected": {"class": expected_class, "description": expected_desc}}
    if expected_class == "cover":
        result.update(verdict="not-a-failure-witness",
                      note="this test replays a cover (an input that reaches it), not a failure: it passes by "
                           "design. Use the test generated for the failing check (`Check for `assertion``, "
                           "`overflow`, ...).")
        emit(result)
        return 2

    work_root = Path(args.work_dir) if args.work_dir else plugin_out_dir(root or path.resolve().parent)
    work_root.mkdir(parents=True, exist_ok=True)
    has_lib = single_file is None and (package / "src" / "lib.rs").exists()
    cwd = path.parent if single_file else package
    cargo_args = args.cargo_arg
    current, current_out, cargo_args = run_witness(cwd, single_file, args.test, cargo_args, None, has_lib)
    isolated = []
    if current == "error" and not single_file:
        # The build failed: replay in a copy of the workspace without the crate's other tests.
        problem = build_problem(current_out)
        work = Path(tempfile.mkdtemp(prefix="witness-", dir=work_root))
        try:
            copy = mirror_workspace(root, work / "ws", exclude=[work_root])
            copy_package = copy / package.relative_to(root)
            isolate(copy_package, args.test)
            relax_warnings(copy_package)
            isolated = ["tests", "deny-warnings"]
            if problem == "needs-std":
                add_std_imports(copy_package, args.test)
                isolated.append("std-imports")
            env = {**kani_env(), "CARGO_TARGET_DIR": str(work / "target")}
            retry, retry_out, retry_args = run_witness(copy_package, None, args.test, args.cargo_arg, env, has_lib)
        finally:
            shutil.rmtree(work, ignore_errors=True)
        if retry != "error":
            current, current_out, cargo_args = retry, retry_out, retry_args
        else:
            current_out += "\n--- retry in a work copy ---\n" + retry_out
            isolated = []
            problem = build_problem(retry_out) or problem
            if problem == "missing-include":
                result["hint"] = ("the crate's tests include files that are missing from this checkout "
                                  "(include_bytes!/include_str!): restore them, or replay in a copy with empty "
                                  "stand-ins")
    current_panic = panic_of(current_out)
    leftover = current_panic is not None and LEFTOVER in current_panic[1]
    verdict_match = matches(current_panic, expected_desc) if current == "fails" and not leftover else None
    if current == "fails" and not leftover and verdict_match is False:
        current = "fails-differently"
    result["current"] = current
    if verdict_match is None and current == "fails" and not leftover:
        result["expectation"] = ("none: no `Check for` doc comment and no --expect, so any panic confirms the "
                                 "defect; pass --expect to check that it is the failure you mean")
    if current_panic:
        result["panic"] = {"location": current_panic[0], "message": current_panic[1]}
    if cargo_args != args.cargo_arg:
        result["cargo_args"] = cargo_args
    if isolated:
        result["isolated"] = ("replayed in a work copy: " + ", ".join(isolated) + " (the crate's other tests removed, "
                              "`deny(warnings)` relaxed, std imports added for a no_std crate); the code under "
                              "verification is unchanged")
    stubs = stubs_of(files, replayed_harness(witness_src))
    if stubs:
        result["harness_stubs"] = stubs
    outputs = [current_out]
    if args.base or args.base_dir:
        if single_file:
            work = Path(tempfile.mkdtemp(prefix="witness-", dir=work_root))
            copy_files = {path.resolve(): work / path.name}
            run_cwd = work
            base_root = path.resolve().parent
        else:
            work = Path(tempfile.mkdtemp(prefix="witness-", dir=work_root))
            copy = mirror_workspace(root, work / "ws", exclude=[work_root])
            copy_files = {f.resolve(): copy / f.resolve().relative_to(root) for f in files}
            run_cwd = copy / package.relative_to(root)
            base_root = root
        try:
            missing_witness_file = False
            for f, target in copy_files.items():
                text = base_text(args, base_root, f)
                if text is None:
                    if f == witness_file.resolve():
                        missing_witness_file = True
                    continue
                if f == witness_file.resolve():
                    text = with_witness(text, witness_src, f)
                    if text is None:
                        print("error: the harness replayed by the witness does not exist in the baseline",
                              file=sys.stderr)
                        return 1
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
            if missing_witness_file:
                print(f"error: `{witness_file}` does not exist at the baseline, so the witness cannot be replayed "
                      "there; commit the witness (and its harness) before the fix", file=sys.stderr)
                return 1
            if isolated:
                isolate(run_cwd, args.test)
                relax_warnings(run_cwd)
                if "std-imports" in isolated:
                    add_std_imports(run_cwd, args.test)
            env = {**kani_env(), "CARGO_TARGET_DIR": str(work / "target")}
            base, base_out, _ = run_witness(run_cwd, single_file, args.test, cargo_args, env, has_lib)
        finally:
            shutil.rmtree(work, ignore_errors=True)
        if base == "fails" and matches(panic_of(base_out), expected_desc) is False:
            base = "fails-differently"
        result["base"] = base
        outputs.append(base_out)
        if "error" in (base, current):
            verdict = "error"
        elif base == "fails" and current == "passes":
            verdict = "fix-confirmed"
        elif base == "fails" and current == "fails":
            verdict = "defect-still-present"
        elif "fails-differently" in (base, current):
            verdict = "different-failure"
        else:
            verdict = "witness-does-not-reproduce"
    else:
        verdict = {"fails": "defect-confirmed", "passes": "witness-does-not-reproduce",
                   "fails-differently": "different-failure"}.get(current, "error")
    if leftover:
        verdict = "spurious-failure-likely"
        result["note"] = ("the replay ended with concrete values left over: Kani's model (with its stubs) consumed "
                          "nondeterministic values that the real code does not, so this witness does not describe "
                          "an execution of the real code.")
    elif stubs and verdict == "witness-does-not-reproduce" and not (args.base or args.base_dir):
        verdict = "spurious-failure-likely"
        result["note"] = ("the harness uses stubs or verified contracts, but playback runs the real code, which "
                          "passes on this input. The failure is most likely caused by a stub or a callee "
                          "contract whose `ensures` is too weak.")
    elif stubs and "note" not in result:
        result["note"] = ("the harness uses stubs or verified contracts, but playback runs the real code: this "
                          "verdict is about the real code, not about what Kani checked.")
    if verdict == "witness-does-not-reproduce" and "note" not in result:
        result["note"] = ("the test passes natively. Native execution does not trap every undefined behavior "
                          "(out-of-bounds pointer arithmetic, invalid pointers, uninitialized reads): if Kani "
                          "reported a memory-safety failure, confirm it with Miri "
                          f"(`cargo +nightly miri test {args.test}`) and report it as Kani-only evidence.")
    result["verdict"] = verdict
    if verdict not in ("defect-confirmed", "fix-confirmed"):
        result["output_tail"] = "\n".join("\n".join(outputs).splitlines()[-OUTPUT_TAIL_LINES:])
    emit(result)
    return 0 if verdict in ("defect-confirmed", "fix-confirmed") else 2


if __name__ == "__main__":
    sys.exit(main())
